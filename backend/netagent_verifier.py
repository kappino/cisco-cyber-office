"""netAgent-powered Mission Verifier for Cisco Cyber Office.

Compares the configuration / state produced by the player against the ideal
mission configuration using CiscoConfParse (reusing netAgent's deterministic
diff/verification approach) and structured rule assertions.
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Optional

try:
    from ciscoconfparse import CiscoConfParse  # type: ignore
    HAS_CISCOCONFPARSE = True
except ImportError:
    HAS_CISCOCONFPARSE = False


def _normalize_iface(name: str) -> str:
    """Normalize Cisco IOS interface names (e.g. gi0/1 -> GigabitEthernet0/1)."""
    s = name.strip().lower()
    s = re.sub(r"^(gi|gig|gigabitethernet)\s*", "GigabitEthernet", s)
    s = re.sub(r"^(fa|fast|fastethernet)\s*", "FastEthernet", s)
    s = re.sub(r"^(eth|ethernet)\s*", "Ethernet", s)
    return s


def commands_to_running_config(commands: List[str]) -> List[str]:
    """Reconstruct a hierarchical Cisco IOS running-config block from CLI commands."""
    lines: List[str] = []
    current_iface: Optional[str] = None

    for raw in commands:
        cmd = raw.strip()
        if not cmd:
            continue
        low = cmd.lower()
        if low in ("enable", "en", "configure terminal", "conf t", "end", "write memory", "wr"):
            if low == "end":
                current_iface = None
            continue
        if low == "exit":
            current_iface = None
            continue

        iface_match = re.match(r"^(?:int|interface)\s+(.+)$", cmd, re.IGNORECASE)
        if iface_match:
            current_iface = _normalize_iface(iface_match.group(1))
            lines.append(f"interface {current_iface}")
            continue

        if current_iface:
            lines.append(f" {cmd}")
        else:
            lines.append(cmd)

    return lines


