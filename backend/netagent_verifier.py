def register_mission_spec(mission_id: str, spec: Dict[str, Any]) -> None:
    """Register or update a dynamic mission spec generated by the LLM Topology Agent."""
    MISSION_SPECS[mission_id] = spec


def _check_ios_rules(
    running_config: List[str], rules: List[Dict[str, Any]]
) -> tuple[List[str], List[str], List[str]]:
    """Evaluate IOS rules against reconstructed config using CiscoConfParse when available."""
    matched: List[str] = []
    missing: List[str] = []
    diff_lines: List[str] = []

    if HAS_CISCOCONFPARSE and running_config:
        parse = CiscoConfParse(running_config, syntax="ios")
        for rule in rules:
            target_iface = _normalize_iface(rule["iface"]).lower()
            found = False
            for obj in parse.find_objects(r"^interface\s+"):
                if target_iface in obj.text.lower():
                    for child in obj.children:
                        if re.search(rule["child_regex"], child.text, re.IGNORECASE):
                            found = True
                            break
            if found:
                matched.append(rule["label"])
            else:
                missing.append(rule["label"])
                diff_lines.append(rule["fix_cmd"])
    else:
        joined = "\n".join(running_config)
        for rule in rules:
            if re.search(rule["child_regex"], joined, re.IGNORECASE):
                matched.append(rule["label"])
            else:
                missing.append(rule["label"])
                diff_lines.append(rule["fix_cmd"])

    return matched, missing, diff_lines


def verify_mission(
    mission_id: str,
    player_commands: List[str],
    player_state: Dict[str, Any],
) -> Dict[str, Any]:
    """Compare player-produced configuration/state with the ideal mission spec."""
    spec = MISSION_SPECS.get(mission_id)
    if not spec:
        return {
            "mission_id": mission_id,
            "passed": False,
            "score_pct": 0,
            "osi_layer": "Unknown",
            "matched": [],
            "missing": [f"Specifica missione '{mission_id}' non trovata"],
            "diff_lines": [],
            "ideal_config": [],
            "source": "netagent_ciscoconfparse" if HAS_CISCOCONFPARSE else "netagent_regex",
        }

    matched: List[str] = []
    missing: List[str] = []
    diff_lines: List[str] = []

    if mission_id == "rack":
        patched = player_state.get("patched_ports", {})
        for port in spec["ideal_ports"]:
            if patched.get(port):
                matched.append(f"Porta {port} cablata e UP")
            else:
                missing.append(f"Porta {port} scollegata")
                diff_lines.append(f"patch {port} -> UP")
    elif mission_id == "umbrella":
        blocked = [d.lower() for d in player_state.get("blocked_domains", [])]
        for dom in spec["required_blocked_domains"]:
            if dom in blocked:
                matched.append(f"Dominio {dom} in sinkhole DNS")
            else:
                missing.append(f"Dominio {dom} non ancora bloccato")
                diff_lines.append(f"umbrella block {dom}")
        if player_state.get("endpoint_isolated"):
            matched.append("Endpoint compromesso isolato")
        else:
            missing.append("Endpoint compromesso non isolato")
            diff_lines.append("isolate endpoint")
    else:
        running_cfg = commands_to_running_config(player_commands)
        rules = spec.get("rules", [])
        if rules:
            matched, missing, diff_lines = _check_ios_rules(running_cfg, rules)
        else:
            # Generic fallback check for custom specs with ideal_config lines
            joined = "\n".join(running_cfg).lower()
            for line in spec.get("ideal_config", []):
                clean = line.strip()
                if not clean or clean.startswith("!"):
                    continue
                if clean.lower() in joined:
                    matched.append(clean)
                else:
                    missing.append(f"Manca: {clean}")
                    diff_lines.append(clean)

    total = len(matched) + len(missing)
    score_pct = int(round((len(matched) / total) * 100)) if total > 0 else 100
    passed = len(missing) == 0 and total > 0

    return {
        "mission_id": mission_id,
        "title": spec.get("title", mission_id),
        "passed": passed,
        "score_pct": score_pct,
        "osi_layer": spec.get("osi_layer", "Layer 1-7"),
        "matched": matched,
        "missing": missing,
        "diff_lines": diff_lines,
        "ideal_config": spec.get("ideal_config", []),
        "source": "netagent_ciscoconfparse" if HAS_CISCOCONFPARSE else "netagent_regex",
    }
